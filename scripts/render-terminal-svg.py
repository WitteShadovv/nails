"""Render captured terminal output as a terminal-styled SVG.

The README and docs show NAILS output as SVG "screenshots". Each one is
rendered from a plain-text capture of real output, kept next to it under
docs/assets/screenshots/, so it can be checked, regenerated and diffed.
Nothing in the picture is typed by hand: the capture holds the output exactly
as the command printed it, and a header says where it came from.

A capture file looks like this:

    title: nails check
    command: sudo /mnt/data/nails check
    caption: Where the output came from (shown under the window).
    ---
    <the output, verbatim>

`title`, `command` and `caption` are optional. Long lines are wrapped at
--columns with a hanging indent; the wrap is the only change made to the text.
Status markers ([PASS], [WARN], [FAIL], [INFO], [-]) are coloured the way the
CLI colours them on a terminal.

Usage:
    scripts/render-terminal-svg.py CAPTURE.txt OUT.svg
    scripts/render-terminal-svg.py --all docs/assets/screenshots
    scripts/render-terminal-svg.py --all docs/assets/screenshots --check

--all renders every *.txt in the directory to the .svg of the same name;
--check renders in memory and fails when a committed SVG differs.

Standard library only, so it runs anywhere Python 3 does.
"""

from __future__ import annotations

import argparse
import re
import sys
import textwrap
from pathlib import Path
from xml.sax.saxutils import escape

FONT_SIZE = 13
LINE_HEIGHT = 18
CHAR_WIDTH = 7.83  # advance of a 13px monospace glyph, close enough for layout
PAD_X = 16
PAD_TOP = 14
TITLE_BAR = 30
CAPTION_GAP = 10

BG = "#0f1419"
BAR = "#1c232b"
FG = "#d5dde6"
MUTED = "#8a96a3"
PROMPT = "#9fb7d6"
MARKERS = {
    "[PASS]": "#7ec699",
    "[WARN]": "#e0b45c",
    "[FAIL]": "#ef7a7a",
    "[INFO]": "#7fb0e0",
    "[-]": MUTED,
}
MARKER_RE = re.compile("(" + "|".join(re.escape(m) for m in MARKERS) + ")")

FONT = "ui-monospace, SFMono-Regular, Menlo, Consolas, 'DejaVu Sans Mono', monospace"
SANS = "system-ui, -apple-system, 'Segoe UI', Helvetica, Arial, sans-serif"


def parse_capture(text: str) -> tuple[dict[str, str], list[str]]:
    """Split a capture into its header fields and its output lines."""
    header: dict[str, str] = {}
    if "\n---\n" in text:
        head, body = text.split("\n---\n", 1)
        for line in head.splitlines():
            key, sep, value = line.partition(":")
            if sep:
                header[key.strip().lower()] = value.strip()
    else:
        body = text
    lines = body.rstrip("\n").split("\n")
    return header, lines


def wrap(line: str, columns: int) -> list[str]:
    """Wrap one output line, continuing with a hanging indent."""
    if len(line) <= columns:
        return [line]
    indent = len(line) - len(line.lstrip(" "))
    hang = " " * min(indent + 4, columns // 2)
    return textwrap.wrap(
        line,
        width=columns,
        subsequent_indent=hang,
        break_long_words=True,
        break_on_hyphens=False,
        drop_whitespace=True,
    ) or [""]


def tspans(line: str) -> str:
    """The SVG markup of one line, with status markers coloured."""
    parts = []
    for chunk in MARKER_RE.split(line):
        if not chunk:
            continue
        colour = MARKERS.get(chunk)
        if colour:
            bold = f'<tspan fill="{colour}" font-weight="bold">'
            parts.append(f"{bold}{escape(chunk)}</tspan>")
        else:
            parts.append(escape(chunk))
    return "".join(parts)


def render(text: str, columns: int) -> str:
    header, lines = parse_capture(text)
    rows: list[str] = []
    command = header.get("command")
    if command:
        for i, part in enumerate(wrap(command, columns - 2)):
            prefix = "$ " if i == 0 else "  "
            rows.append(
                f'<tspan fill="{PROMPT}">{escape(prefix)}</tspan>'
                f'<tspan fill="{FG}" font-weight="bold">{escape(part)}</tspan>'
            )
    for line in lines:
        for part in wrap(line.expandtabs(8), columns):
            rows.append(tspans(part))

    caption = header.get("caption", "")
    caption_lines = textwrap.wrap(caption, width=int(columns * 1.12)) if caption else []

    width = round(PAD_X * 2 + columns * CHAR_WIDTH)
    body_h = PAD_TOP + len(rows) * LINE_HEIGHT + PAD_TOP
    window_h = TITLE_BAR + body_h
    caption_h = (CAPTION_GAP + len(caption_lines) * 17) if caption_lines else 0
    height = window_h + caption_h + 2

    title = escape(header.get("title", ""))
    out = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- Generated by scripts/render-terminal-svg.py"
        " from the .txt capture of the same name. -->",
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" '
        f'aria-label="Terminal output: {title}">',
        f'<rect x="0.5" y="0.5" width="{width - 1}" height="{window_h}" rx="8" '
        f'fill="{BG}" stroke="#2b3540"/>',
        f'<path d="M0.5 {TITLE_BAR}V8.5a8 8 0 0 1 8-8H{width - 8.5}'
        f'a8 8 0 0 1 8 8V{TITLE_BAR}z" fill="{BAR}"/>',
    ]
    for i in range(3):
        cy = TITLE_BAR / 2 + 0.5
        out.append(f'<circle cx="{18 + i * 16}" cy="{cy}" r="5" fill="#4b5561"/>')
    if title:
        out.append(
            f'<text x="{width / 2}" y="{TITLE_BAR / 2 + 5}" text-anchor="middle" '
            f'font-family="{SANS}" font-size="12" fill="{MUTED}">{title}</text>'
        )
    out.append(
        f'<text font-family="{FONT}" font-size="{FONT_SIZE}" fill="{FG}" '
        'xml:space="preserve">'
    )
    y = TITLE_BAR + PAD_TOP + FONT_SIZE
    for row in rows:
        out.append(f'<tspan x="{PAD_X}" y="{y}">{row}</tspan>')
        y += LINE_HEIGHT
    out.append("</text>")
    y = window_h + CAPTION_GAP + 12
    for line in caption_lines:
        out.append(
            f'<text x="2" y="{y}" font-family="{SANS}" font-size="12" '
            f'fill="#7b8794">{escape(line)}</text>'
        )
        y += 17
    out.append("</svg>")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("source", help="a capture .txt, or a directory with --all")
    parser.add_argument("output", nargs="?", help="the .svg to write")
    parser.add_argument(
        "--all", action="store_true", help="render every *.txt in SOURCE"
    )
    parser.add_argument(
        "--check", action="store_true", help="fail if a committed SVG is stale"
    )
    parser.add_argument(
        "--columns", type=int, default=100, help="wrap width (default 100)"
    )
    args = parser.parse_args(argv)

    if args.all:
        captures = sorted(Path(args.source).glob("*.txt"))
        pairs = [(p, p.with_suffix(".svg")) for p in captures]
    else:
        if not args.output:
            parser.error("OUT.svg is required without --all")
        pairs = [(Path(args.source), Path(args.output))]

    stale = []
    for capture, svg in pairs:
        rendered = render(capture.read_text(encoding="utf-8"), args.columns)
        if args.check:
            if not svg.exists() or svg.read_text(encoding="utf-8") != rendered:
                stale.append(str(svg))
        else:
            svg.write_text(rendered, encoding="utf-8")
            print(f"rendered {svg}")
    if stale:
        names = ", ".join(stale)
        print(f"stale screenshot(s), re-run without --check: {names}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
