#[test]
fn the_audit_changes_nothing_and_keeps_access_times() {
    let root = clean_root();
    let vault = root.path().join("home/alice/vault.hc");
    std::fs::write(&vault, container(2 << 20)).unwrap();
    let old = std::time::SystemTime::UNIX_EPOCH + std::time::Duration::from_secs(1_000_000_000);
    std::fs::File::open(&vault)
        .unwrap()
        .set_times(std::fs::FileTimes::new().set_accessed(old))
        .unwrap();
    let before = std::fs::metadata(&vault).unwrap();

    let report = examine(root.path(), &ExaminerOptions::default());

    assert!(ids(&report).contains("container-candidates"));
    let after = std::fs::metadata(&vault).unwrap();
    assert_eq!(after.atime(), before.atime(), "the audit updated an atime");
    assert_eq!(after.mtime(), before.mtime());
    assert_eq!(after.ctime(), before.ctime());
}

/// A 64 MiB MBR image: p1 ext4 at 1 MiB (8 MiB), p2 at 16 MiB (8 MiB) and the
/// rest unpartitioned. `seed` decides what p2 and the gaps hold.
fn disk_image(dir: &tempfile::TempDir, seeded: bool) -> PathBuf {
    use crate::forensic::layout::tests::{mbr_image, put};
    let (path, mut file) = mbr_image(dir, 64 << 20, &[(0x83, 2048, 16384), (0x83, 32768, 16384)]);
    put(&mut file, (1 << 20) + 0x438, &[0x53, 0xEF]);
    if seeded {
        // p2 is a LUKS2 volume, the gap between p1 and p2 holds random data,
        // and the tail after p2 holds a headerless random region.
        put(&mut file, 16 << 20, b"LUKS\xba\xbe\x00\x02");
        put(&mut file, 9 << 20, &random(7 << 20));
        put(&mut file, 24 << 20, &random(40 << 20));
    } else {
        put(&mut file, 16 << 20 | 0x438, &[0x53, 0xEF]);
    }
    file.sync_all().unwrap();
    path
}

#[test]
fn the_disk_audit_finds_headers_and_random_space() {
    let dir = tempfile::tempdir().unwrap();
    let options = ExaminerOptions {
        disk: Some(disk_image(&dir, true)),
        ..ExaminerOptions::default()
    };
    let root = clean_root();

    let report = examine(root.path(), &options);

    assert!(report.checks_run.contains(&"examiner-disk"));
    let disk: Vec<&ExaminerFinding> = report
        .findings()
        .filter(|f| matches!(f.catalog_id, "luks-headers" | "high-entropy-space"))
        .collect();
    assert!(
        disk.iter()
            .any(|f| f.catalog_id == "luks-headers" && f.location.starts_with("partition 2")),
        "{disk:#?}"
    );
    let random_regions: Vec<&&ExaminerFinding> = disk
        .iter()
        .filter(|f| f.catalog_id == "high-entropy-space")
        .collect();
    assert_eq!(random_regions.len(), 2, "{disk:#?}");
}

