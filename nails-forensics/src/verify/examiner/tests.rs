#[test]
fn verify_carries_the_audit_without_changing_its_status() {
    let root = clean_root();
    write(root.path(), "/var/lib/udisks2/drive.conf", b"[Drive]\n");
    write(root.path(), "/home/alice/vault.hc", &random(2 << 20));

    let result = crate::Verifier::new(crate::RealFilesystem)
        .offline_under(root.path().to_path_buf())
        .with_examiner(ExaminerOptions::default())
        .run(false)
        .unwrap();

    let report = result.examiner.as_ref().expect("the audit ran");
    assert!(ids(report).contains("udisks2-state"));
    assert!(ids(report).contains("container-candidates"));
    // The session-residue status is unaffected by setup traces.
    assert_eq!(
        result.status,
        crate::VerifyStatus::Secure,
        "{:?}",
        result.findings
    );
    // Without --disk the partition-level classes are listed as not checked.
    assert!(
        result
            .areas_not_checked
            .iter()
            .any(|area| area.contains("LUKS headers on partitions") && area.contains("--disk")),
        "{:?}",
        result.areas_not_checked
    );
    // The setup-trace summary line is gone once the audit ran.
    assert!(
        !result
            .areas_not_checked
            .iter()
            .any(|area| area.starts_with("setup traces an examiner looks for")),
        "{:?}",
        result.areas_not_checked
    );
}

