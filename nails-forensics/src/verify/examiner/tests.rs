use super::*;
use std::io::Read;
use std::os::unix::fs::MetadataExt;

fn random(len: usize) -> Vec<u8> {
    let mut bytes = vec![0u8; len];
    std::fs::File::open("/dev/urandom")
        .unwrap()
        .read_exact(&mut bytes)
        .unwrap();
    bytes
}

/// What a container file holds: random bytes behind a start that no format
/// the examiner knows begins with. A random start is gzip's two-byte magic in
/// one file of 65536, and the audit then rightly takes it for no container.
fn container(len: usize) -> Vec<u8> {
    let mut bytes = random(len);
    bytes[..8].copy_from_slice(b"\x01\x02\x03\x04\x05\x06\x07\x08");
    bytes
}

fn write(root: &Path, rel: &str, bytes: &[u8]) {
    let path = root.join(rel.trim_start_matches('/'));
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, bytes).unwrap();
}

fn ids(report: &ExaminerReport) -> BTreeSet<&'static str> {
    report
        .findings()
        .map(|finding| finding.catalog_id)
        .collect()
}

use std::collections::BTreeSet;

/// A decoy root holding nothing an examiner would flag.
fn clean_root() -> tempfile::TempDir {
    let root = tempfile::tempdir().unwrap();
    write(
        root.path(),
        "/etc/passwd",
        b"root:x:0:0::/root:/bin/sh\nalice:x:1000:100::/home/alice:/bin/bash\n",
    );
    write(
        root.path(),
        "/etc/fstab",
        b"/dev/vda1 / ext4 defaults 0 1\n",
    );
    write(
        root.path(),
        "/home/alice/.bash_history",
        b"ls\nvim notes.txt\n",
    );
    write(root.path(), "/home/alice/notes.txt", b"plain notes\n");
    // A large but compressible file and a large compressed one with a header.
    write(root.path(), "/home/alice/big.txt", &vec![b'a'; 2 << 20]);
    let mut gz = b"\x1f\x8b".to_vec();
    gz.extend(random((2 << 20) - 2));
    write(root.path(), "/home/alice/archive.gz", &gz);
    root
}

